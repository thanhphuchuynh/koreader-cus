local m=I.score(t,{[3]={'D','A'}});assert(m.rows[3].ok==false and m.rows[3].answer=='D' and m.rows[3].correct=='B' and m.rows[4].ok and m.rows[4].correct=='A','multi wrong row names the unpicked key letter')
m=I.score(t,{});assert(m.rows[3].correct=='A' and m.rows[4].correct=='B')
